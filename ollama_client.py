"""Optional Metal-backed local serving; no torch dependency or fake logprobs."""
import json
import time
import urllib.error
import urllib.request
from urllib.parse import urlsplit

from config import ROUTE_LOCAL, settings
from schemas import Completion
from generation_context import completion_messages, output_limit, TOOLS, LOCAL_CONTEXT


def local_system_prompt(model):
    """Give the model deployment facts it cannot infer from its training."""
    host = urlsplit(settings.ollama_base_url).hostname
    if host in {"127.0.0.1", "localhost", "::1"}:
        location = (
            "This reply is generated locally on the computer running Nana, "
            "through a loopback Ollama server. It is not a cloud API call. "
        )
    else:
        location = (
            "This reply is generated by the configured Ollama server. "
            "Its physical location and model storage are not known from this request. "
        )
    context = (
        "Background runtime facts supplied by Nana, not text to repeat in replies: "
        "Your assistant name is Nana. "
        "When specifically asked your name, simply answer Nana. "
        "You operate inside Nana, a user-built chat application. "
        f"The selected model ID is {model}. "
        "Mention the underlying model ID when specifically asked which model "
        "powers you; your assistant name remains Nana. "
        + location +
        "The app's creator built the application, which is distinct from training "
        "the underlying model. Model files can be stored on an SSD; inference "
        "executes on the host's processor using memory, not on the SSD itself. "
        "Do not invent your developer, hosting provider, hardware or storage path. "
        "When asked about your deployment, use these runtime facts instead of "
        "contradictory identity claims in earlier assistant replies. "
        "Keep these facts in the background. Do not volunteer your name, model ID, "
        "local status, Ollama or server details in ordinary replies or greetings. "
        "Only disclose the specific identity or runtime detail the user asks for. "
        "A greeting needs only a natural brief greeting, with no self-introduction. "
        "In an ongoing conversation, answer the current request directly; do not "
        "restart the conversation or repeat an introduction from earlier replies."
    )
    return "\n\n".join(part for part in (settings.system_prompt, context) if part)


def _num_ctx():
    """Per-request context (chat profiles) first, then LOCAL_CONTEXT_TOKENS."""
    return LOCAL_CONTEXT.get() or settings.local_context_tokens or None


def build_chat_payload(model, messages, stream):
    """The /api/chat request body. generate(), stream_generate() and the
    router identity (routing/identity.py) all use this one builder, so the
    identity describes what is actually sent, request overrides included."""
    ctx = _num_ctx()
    return {"model": model, "messages": messages, "stream": stream, "think": False,
            **({"tools": TOOLS.get()} if TOOLS.get() else {}),
            "options": {"temperature": 0, **({"num_ctx": ctx} if ctx else {}),
                        "num_predict": output_limit(settings.local_max_new_tokens)}}


def request(path, payload=None, timeout=120):
    body = json.dumps(payload).encode() if payload is not None else None
    req = urllib.request.Request(settings.ollama_base_url.rstrip("/") + path,
                                 data=body, headers={"Content-Type": "application/json"})
    try:
        with urllib.request.urlopen(req, timeout=timeout) as response:
            data = json.load(response)
    except urllib.error.HTTPError as exc:
        raise RuntimeError(f"Ollama returned HTTP {exc.code}; check the model is installed") from None
    except urllib.error.URLError:
        raise RuntimeError("Ollama is unavailable. Start Ollama and install the selected model.") from None
    if data.get("error"):
        raise RuntimeError(str(data["error"]))
    return data


def generate(model, prompt):
    started = time.monotonic()
    messages = completion_messages(prompt, local_system_prompt(model))
    if TOOLS.get():
        # Ollama accepts object arguments; OpenAI-compatible remote APIs use
        # JSON strings. Translate at the provider boundary, preserving roles.
        for message in messages:
            if message.get("tool_calls"):
                message["tool_calls"] = [dict(call, function={**call["function"], "arguments": json.loads(call["function"]["arguments"]) if isinstance(call["function"].get("arguments"), str) else call["function"].get("arguments", {})}) for call in message["tool_calls"]]
    from generation_stream import CURRENT
    if CURRENT.get() is not None:
        return stream_generate(model, messages, CURRENT.get(), started)
    data = request("/api/chat", build_chat_payload(model, messages, stream=False))
    raw = data["message"].get("content", "")
    return Completion(text=raw.strip(),
                      tool_calls=data["message"].get("tool_calls", []),
                      prompt_tokens=int(data.get("prompt_eval_count", 0)),
                      completion_tokens=int(data.get("eval_count", 0)),
                      source=ROUTE_LOCAL, model_name=model, provider="local",
                      latency_s=time.monotonic() - started, **_provenance(data, raw))


# Ollama reports durations in nanoseconds on the final response object.
_TIMING_FIELDS = ("total_duration", "load_duration", "prompt_eval_duration", "eval_duration")


def _provenance(final, raw):
    """finish_reason / usage_source / timings / raw_text from a final Ollama response."""
    counted = "prompt_eval_count" in final and "eval_count" in final
    return {
        "finish_reason": final.get("done_reason"),
        "usage_source": "provider" if counted else "",
        "timings": {k[:-len("_duration")] + "_s": final[k] / 1e9
                    for k in _TIMING_FIELDS if isinstance(final.get(k), (int, float))},
        "raw_text": raw,
    }


def model_identity(model):
    """Deployment facts the runtime reports for ``model``: digest, quantisation,
    format, family, parameter size, and the runtime version. Raises
    RuntimeError when Ollama is unreachable; missing facts are None, never guessed."""
    show = request("/api/show", {"model": model}, timeout=10)
    tags = request("/api/tags", timeout=10).get("models", [])
    digest = next((m.get("digest") for m in tags if m.get("name") == model or m.get("model") == model), None)
    try:
        version = request("/api/version", timeout=10).get("version")
    except RuntimeError:
        version = None
    details = show.get("details") or {}
    return {
        "digest": digest,
        "quantization": details.get("quantization_level"),
        "format": details.get("format"),
        "family": details.get("family"),
        "parameter_size": details.get("parameter_size"),
        "template_sha256": _metadata_sha256(show, "template"),
        "parameters_sha256": _metadata_sha256(show, "parameters"),
        "runtime_version": version,
    }


# The /api/show response answered but did not include the field: a reported
# fact, distinct from None (unknown because nothing was reported).
ABSENT_IN_RESPONSE = "absent_in_runtime_response"


def _metadata_sha256(show, key):
    """Hash of a /api/show field. Text is hashed exactly as returned;
    structured values are canonicalised (sorted keys) without altering any
    string inside them. Unknown shapes stay None, never guessed."""
    import hashlib
    if key not in show:
        return ABSENT_IN_RESPONSE
    value = show[key]
    if isinstance(value, str):
        blob = value
    elif isinstance(value, (dict, list)):
        blob = json.dumps(value, sort_keys=True, ensure_ascii=True, separators=(",", ":"))
    else:
        return None
    return hashlib.sha256(blob.encode("utf-8")).hexdigest()


def stream_generate(model, messages, stream, started):
    stream.start("local", model)
    payload = build_chat_payload(model, messages, stream=True)
    req = urllib.request.Request(settings.ollama_base_url.rstrip("/") + "/api/chat",
                                 data=json.dumps(payload).encode(), headers={"Content-Type": "application/json"})
    pieces, final, calls = [], {}, []
    try:
        with urllib.request.urlopen(req, timeout=stream.remaining(settings.request_timeout_s)) as response:
            for line in response:
                stream.check()
                data = json.loads(line)
                if data.get("error"):
                    raise RuntimeError(str(data["error"]))
                calls.extend(data.get("message", {}).get("tool_calls", []))
                text = data.get("message", {}).get("content", "")
                if text:
                    pieces.append(text)
                    stream.delta(text)
                if data.get("done"):
                    final = data
                    stream.usage({"prompt_tokens": final.get("prompt_eval_count", 0), "completion_tokens": final.get("eval_count", 0)})
    except urllib.error.HTTPError as exc:
        if exc.code == 404:
            raise RuntimeError(
                f"Ollama model {model!r} is not installed. Choose an installed local model in Chat."
            ) from None
        raise RuntimeError(f"Ollama returned HTTP {exc.code} while streaming {model!r}") from None
    except urllib.error.URLError:
        raise RuntimeError("Ollama streaming connection failed; check that the configured runtime is running") from None
    if not final.get("done"):
        raise RuntimeError("Ollama stream ended before completion; usage may be incomplete")
    raw = "".join(pieces)
    return Completion(text=raw.strip(), tool_calls=calls, prompt_tokens=int(final.get("prompt_eval_count", 0)),
                      completion_tokens=int(final.get("eval_count", 0)), source=ROUTE_LOCAL,
                      model_name=model, provider="local", latency_s=time.monotonic()-started,
                      **_provenance(final, raw))
